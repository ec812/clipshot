import XCTest
@testable import Clipshot

final class PrivacyFilterTests: XCTestCase {
    private var now: Date!

    override func setUp() {
        super.setUp()
        now = Date(timeIntervalSince1970: 1_700_000_000)
    }

    private func makeFilter(
        ignored: Set<String> = ["com.1password.1password"],
        skipTransient: Bool = true,
        skipConcealed: Bool = true
    ) -> PrivacyFilter {
        let configuration = PrivacyFilterConfiguration(
            ignoredBundleIds: ignored,
            skipTransient: skipTransient,
            skipConcealed: skipConcealed
        )
        return PrivacyFilter(configuration: configuration, now: { [weak self] in
            self?.now ?? Date()
        })
    }

    func testCapturesNormalContent() {
        let filter = makeFilter()
        XCTAssertTrue(filter.shouldCapture(bundleId: "com.apple.Safari", pasteboardTypes: ["public.utf8-plain-text"]))
    }

    func testIgnoresConfiguredBundles() {
        let filter = makeFilter()
        XCTAssertFalse(filter.shouldCapture(bundleId: "com.1password.1password", pasteboardTypes: ["public.utf8-plain-text"]))
        XCTAssertFalse(filter.shouldCapture(bundleId: "COM.1PASSWORD.1PASSWORD", pasteboardTypes: []))
        XCTAssertFalse(filter.shouldCapture(bundleId: nil, pasteboardTypes: [], sourceApp: "com.1password.1password"))
    }

    func testSkipsTransientAndAutoGeneratedMarkers() {
        let filter = makeFilter()
        XCTAssertFalse(filter.shouldCapture(
            bundleId: "com.apple.Safari",
            pasteboardTypes: ["public.utf8-plain-text", "org.nspasteboard.TransientType"]
        ))
        XCTAssertFalse(filter.shouldCapture(
            bundleId: "com.apple.Safari",
            pasteboardTypes: ["org.nspasteboard.AutoGeneratedType"]
        ))
    }

    func testTransientMarkersCanBeIgnoredWhenDisabled() {
        let filter = makeFilter(skipTransient: false)
        XCTAssertTrue(filter.shouldCapture(
            bundleId: "com.apple.Safari",
            pasteboardTypes: ["org.nspasteboard.TransientType"]
        ))
    }

    func testSkipsConcealedMarkers() {
        let filter = makeFilter()
        XCTAssertFalse(filter.shouldCapture(
            bundleId: "com.apple.Safari",
            pasteboardTypes: ["org.nspasteboard.ConcealedType"]
        ))
        XCTAssertFalse(filter.shouldCapture(
            bundleId: "com.apple.Safari",
            pasteboardTypes: ["com.agilebits.onepassword"]
        ))
    }

    func testConcealedMarkersCanBeIgnoredWhenDisabled() {
        let filter = makeFilter(skipConcealed: false)
        XCTAssertTrue(filter.shouldCapture(
            bundleId: "com.apple.Safari",
            pasteboardTypes: ["org.nspasteboard.ConcealedType"]
        ))
    }

    func testPauseBlocksCaptureUntilExpiry() {
        let filter = makeFilter()
        filter.pause(for: 60)
        XCTAssertTrue(filter.isPaused)
        XCTAssertFalse(filter.shouldCapture(bundleId: "com.apple.Safari", pasteboardTypes: []))

        now = now.addingTimeInterval(61)
        XCTAssertFalse(filter.isPaused)
        XCTAssertTrue(filter.shouldCapture(bundleId: "com.apple.Safari", pasteboardTypes: []))
    }

    func testPauseDoesNotShortenLongerWindow() {
        let filter = makeFilter()
        filter.pause(for: 600)
        now = now.addingTimeInterval(10)
        filter.pause(for: 30)
        XCTAssertEqual(filter.pauseRemaining, 590, accuracy: 0.5)
    }

    func testResumeClearsPause() {
        let filter = makeFilter()
        filter.pause(for: 600)
        filter.resume()
        XCTAssertFalse(filter.isPaused)
        XCTAssertTrue(filter.shouldCapture(bundleId: "com.apple.Safari", pasteboardTypes: []))
    }

    func testUpdatingIgnoredBundlesTakesEffect() {
        let filter = makeFilter(ignored: [])
        XCTAssertTrue(filter.shouldCapture(bundleId: "com.example.secret", pasteboardTypes: []))
        filter.setIgnoredBundleIds(["com.example.secret"])
        XCTAssertFalse(filter.shouldCapture(bundleId: "com.example.secret", pasteboardTypes: []))
    }
}
