import Foundation

struct PrivacyFilterConfiguration: Equatable {
    var ignoredBundleIds: Set<String>
    var skipTransient: Bool
    var skipConcealed: Bool

    static let defaultIgnoredBundleIds: Set<String> = [
        "com.1password.1password",
        "com.agilebits.onepassword",
        "com.agilebits.onepassword7",
        "com.bitwarden.desktop",
        "com.lastpass.LastPass",
        "com.dashlane.dashlane",
        "org.keepassxc.keepassxc",
        "com.apple.keychainaccess"
    ]

    static let `default` = PrivacyFilterConfiguration(
        ignoredBundleIds: defaultIgnoredBundleIds,
        skipTransient: true,
        skipConcealed: true
    )
}

/// Decides whether a clipboard change may be captured.
///
/// The heavy lifting is deliberately local and deterministic so it can be unit tested:
/// bundle-id ignore list, nspasteboard.org marker types, and a pause window.
final class PrivacyFilter {
    var configuration: PrivacyFilterConfiguration
    private(set) var pausedUntil: Date?
    private let now: () -> Date

    init(configuration: PrivacyFilterConfiguration = .default, now: @escaping () -> Date = Date.init) {
        self.configuration = configuration
        self.now = now
    }

    var isPaused: Bool {
        guard let pausedUntil else { return false }
        return pausedUntil > now()
    }

    var pauseRemaining: TimeInterval {
        guard let pausedUntil else { return 0 }
        return max(0, pausedUntil.timeIntervalSince(now()))
    }

    func pause(for duration: TimeInterval) {
        let until = now().addingTimeInterval(duration)
        if let pausedUntil, pausedUntil > until {
            return
        }
        pausedUntil = until
    }

    func resume() {
        pausedUntil = nil
    }

    func setIgnoredBundleIds(_ bundleIds: Set<String>) {
        configuration.ignoredBundleIds = bundleIds
    }

    /// `pasteboardTypes` should contain raw pasteboard type identifiers.
    func shouldCapture(
        bundleId: String?,
        pasteboardTypes: Set<String>,
        sourceApp: String? = nil
    ) -> Bool {
        if isPaused { return false }

        if let bundleId {
            let normalized = bundleId.lowercased()
            if configuration.ignoredBundleIds.contains(where: { $0.lowercased() == normalized }) {
                return false
            }
        }

        if let sourceApp, configuration.ignoredBundleIds.contains(where: {
            $0.lowercased() == sourceApp.lowercased()
        }) {
            return false
        }

        if configuration.skipTransient {
            let transientTypes: Set<String> = [
                "org.nspasteboard.TransientType",
                "org.nspasteboard.AutoGeneratedType"
            ]
            if !pasteboardTypes.isDisjoint(with: transientTypes) {
                return false
            }
        }

        if configuration.skipConcealed {
            let concealedTypes: Set<String> = [
                "org.nspasteboard.ConcealedType",
                "com.agilebits.onepassword",
                "com.1password.1password"
            ]
            if !pasteboardTypes.isDisjoint(with: concealedTypes) {
                return false
            }
        }

        return true
    }
}
